"""Guest chat endpoints (HTTP fallback; the primary transport is the WebSocket).

Guests are anonymous: a random ``session_id`` (UUID generated by the browser) is the
conversation key. The id is unguessable, so history is readable only by whoever holds it.
"""
from __future__ import annotations

import uuid
from typing import Literal

from fastapi import APIRouter, Depends, Request
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from app.config import get_settings
from app.db.base import get_db_session
from app.db.models.conversation import Conversation
from app.dependencies import get_runtime

router = APIRouter(prefix="/chat", tags=["chat"])


class ChatRequest(BaseModel):
    """Body of ``POST /chat/message``."""

    message: str = Field(min_length=1, max_length=1000)
    session_id: uuid.UUID | None = None
    language: Literal["en", "ne"] | None = None


@router.post("/message", summary="Send a chat message and get the concierge's reply")
async def post_message(body: ChatRequest, runtime=Depends(get_runtime)) -> dict:  # noqa: B008
    """Run one turn. Returns the reply plus the session id to reuse next time."""
    session_id = body.session_id or uuid.uuid4()
    reply = await runtime.chat.handle_message(
        session_id=session_id, text=body.message, ui_language=body.language
    )
    return reply.to_dict()


@router.get("/history/{session_id}", summary="Conversation history for a chat session")
async def history(session_id: uuid.UUID, session: AsyncSession = Depends(get_db_session)) -> dict:  # noqa: B008
    """Return visible messages (guest, concierge, human agent) in order."""
    conversation = (
        await session.execute(
            select(Conversation)
            .where(Conversation.session_id == session_id)
            .options(selectinload(Conversation.messages))
        )
    ).scalar_one_or_none()
    if conversation is None:
        return {"session_id": str(session_id), "messages": [], "handoff_active": False}
    messages = [
        {"role": m.role, "content": m.content, "created_at": m.created_at.isoformat()}
        for m in sorted(conversation.messages, key=lambda x: x.created_at)
        if m.role in ("user", "assistant", "human_agent")
    ]
    return {
        "session_id": str(session_id), "messages": messages,
        "handoff_active": conversation.status == "handed_off",
    }


@router.get("/capabilities", summary="What the UI may offer (voice, business name)")
async def capabilities(request: Request) -> dict:
    """Tell the UI which voice features the server supports."""
    settings = get_settings()
    runtime = request.app.state.runtime
    return {
        "business_name": settings.business_name,
        "voice_input": runtime.chat.voice_input_available,
        "voice_output": runtime.chat.voice_output_available,
        "languages": ["en", "ne"],
        "max_message_chars": 1000,
    }
